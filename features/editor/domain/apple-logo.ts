export function appleLogoPath(width: number, depth: number): string {
  const scale = (Math.min(width, depth) * 0.2) / 16;
  return outline
    .map(
      ([command, values]) =>
        command +
        ' ' +
        values
          .map((value, index) => {
            // Arc rotation and flags are dimensionless; all other values are lengths.
            return command === 'a' && [2, 3, 4].includes(index % 7)
              ? value
              : value * scale;
          })
          .join(' '),
    )
    .join(' ');
}
